//! Golden tests for the apply, revert and script commands, and their round trip through the
//! fixture backend.

use outlay::backend::{Backend, FixtureBackend, Plan, PrimaryRule};
use outlay::model::layout::Layout;
use outlay::model::{Reflection, Rotation, Snapshot};
use outlay::wayland::capture::parse as parse_capture;
use outlay::xrandr::command::argv_to_plan;
use outlay::xrandr::{command, parse_verbose};

/// The xrandr arguments of the apply of `layout`.
fn apply_args(layout: &Layout, snap: &Snapshot) -> Vec<String> {
    command::argv(&Plan::pending(layout, snap))
}

/// The same apply as `y` copies it.
fn portable_args(layout: &Layout, snap: &Snapshot) -> Vec<String> {
    command::portable_argv(&Plan::pending(layout, snap))
}

/// The xrandr arguments that restore `live`.
fn revert_args(live: &Snapshot) -> Vec<String> {
    command::argv(&Plan::restore(live))
}

fn fixture(name: &str) -> Snapshot {
    let path = format!(
        "{}/tests/fixtures/xrandr/{name}.txt",
        env!("CARGO_MANIFEST_DIR")
    );
    parse_verbose(&std::fs::read_to_string(path).unwrap()).unwrap()
}

fn wayland_fixture(name: &str) -> Snapshot {
    let path = format!(
        "{}/tests/fixtures/wayland/{name}.json",
        env!("CARGO_MANIFEST_DIR")
    );
    parse_capture(&std::fs::read_to_string(path).unwrap()).unwrap()
}

/// The demo with DP-1-3 turned on, HDMI-1-0 one rate up and eDP-1 made primary.
fn edited_demo() -> (Snapshot, Layout) {
    let snap = fixture("demo");
    let (mut layout, _) = Layout::from_snapshot(&snap);
    layout.turn_on(&snap, snap.find("DP-1-3").unwrap()).unwrap();
    layout
        .step_rate(&snap, snap.find("HDMI-1-0").unwrap(), true)
        .unwrap();
    layout.set_primary(snap.find("eDP-1").unwrap()).unwrap();
    (snap, layout)
}

#[test]
fn apply_of_the_unchanged_demo() {
    let snap = fixture("demo");
    let (layout, notes) = Layout::from_snapshot(&snap);
    assert!(notes.is_empty());
    assert!(layout.diff(&snap).is_empty());
    assert_eq!(
        command::command_line(&apply_args(&layout, &snap)),
        "xrandr --output HDMI-1-0 --mode 0x1c3 --pos 0x360 --rotate normal --reflect normal \
         --output DP-1-2 --primary --mode 0x1cb --pos 1920x0 --rotate normal --reflect normal \
         --output eDP-1 --mode 0x1cf --pos 2240x1440 --rotate normal --reflect normal \
         --output DP-1-3 --off"
    );
}

#[test]
fn apply_and_copy_of_an_edited_demo() {
    let (snap, layout) = edited_demo();
    let diff: Vec<String> = layout.diff(&snap).iter().map(ToString::to_string).collect();
    assert_eq!(
        diff,
        [
            "HDMI-1-0  rate 59.94 → 60.00",
            "eDP-1  primary",
            "DP-1-3  off → 3840x2160@60.00"
        ]
    );
    assert_eq!(
        command::command_line(&apply_args(&layout, &snap)),
        "xrandr --output HDMI-1-0 --mode 0x1c4 --pos 0x360 --rotate normal --reflect normal \
         --output DP-1-2 --mode 0x1cb --pos 1920x0 --rotate normal --reflect normal \
         --output eDP-1 --primary --mode 0x1cf --pos 2240x1440 --rotate normal --reflect normal \
         --output DP-1-3 --mode 0x1d6 --pos 4480x0 --rotate normal --reflect normal"
    );
    assert_eq!(
        command::command_line(&portable_args(&layout, &snap)),
        "xrandr --output HDMI-1-0 --mode 1920x1080 --rate 60.00 --pos 0x360 --rotate normal --reflect normal \
         --output DP-1-2 --mode 2560x1440 --rate 143.91 --pos 1920x0 --rotate normal --reflect normal \
         --output eDP-1 --primary --mode 1920x1080 --rate 165.01 --pos 2240x1440 --rotate normal --reflect normal \
         --output DP-1-3 --mode 3840x2160 --rate 60.00 --pos 4480x0 --rotate normal --reflect normal"
    );
}

